"""Shared, content-keyed specification translations, independently checked at certification."""
from dataclasses import dataclass
import errno
import hashlib
import json
from pathlib import Path
import tempfile

from scripts.lean_tools import require_name, require_timeout, run_checked
from scripts.toolchain import PROJECT, SCRATCH_DIRECTORY, digest, resolve_toolchain, source_identity


@dataclass(frozen=True)
class SharedTranslation:
    directory: Path
    module: str
    fingerprints: dict[str, str]


def prepare_translation(spec_paths, catalog_path, *, project=PROJECT,
                        timeout_seconds=120, verify=False):
    """Reuse generated bytes for emission; reconstruct them for check/load auditing.

    A hash in identity.json is a cache hint, not a certificate. Verification
    compares against fresh native output even if those hash claims were edited.
    Different source/tool selections coexist, so one property cannot replace
    the shared dependencies of another property.
    """
    project = Path(project).resolve()
    timeout = require_timeout(timeout_seconds)
    sources = [Path(path).absolute() for path in spec_paths]
    tool = resolve_toolchain(project)
    expected = dict(schema_version=1, spec_paths=list(map(str, sources)), sources=source_identity(sources),
                    toolchain=tool.identity(), options=['--relation-semantics', 'ordered'])
    key = 's' + hashlib.sha256(json.dumps(expected, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    catalog = Path(catalog_path).absolute()
    parent = catalog.parent
    # Non-project inputs and arbitrary temporary directory names still need a
    # valid module path inside the current Lean project.
    try:
        if not (parent.is_relative_to(project/'specifications')
                or parent.is_relative_to(project/SCRATCH_DIRECTORY)):
            raise ValueError('catalog is outside specification or scratch libraries')
        require_name('.'.join(parent.relative_to(project).parts))
    except ValueError:
        parent = project / SCRATCH_DIRECTORY / 'Specifications'
    root = parent/'translated'
    directory = root/key
    for path in [directory, *directory.parents]:
        if path == project:
            break
        if path.is_symlink():
            raise ValueError('shared translation path must not contain a symlink')
    module = '.'.join(directory.relative_to(project).parts) + '.Spec'
    require_name(module)
    source = directory/'Spec.lean'
    identity_path = directory/'identity.json'

    def translate():
        text = run_checked([str(tool.executable), *expected['options'], *map(str, sources)], project, timeout)
        if source_identity(sources) != expected['sources'] or tool.identity() != expected['toolchain']:
            raise ValueError('specification or translator changed during shared translation')
        return text.encode()

    if directory.exists():
        if source.is_symlink() or identity_path.is_symlink():
            raise ValueError('shared translation file must not be a symlink')
        record = json.loads(identity_path.read_text())
        if {k: v for k, v in record.items() if k != 'generated'} != expected:
            raise ValueError('shared translation identity mismatch; regenerate the translation')
        if record.get('generated') != {'Spec.lean': digest(source)}:
            raise ValueError('shared translation content mismatch; regenerate the translation')
        if verify and source.read_bytes() != translate():
            raise ValueError('shared translation source mismatch; regenerate the translation')
    elif verify:
        raise ValueError('shared translation is missing; run emit again')
    else:
        contents = translate()
        record = {**expected, 'generated': {'Spec.lean': hashlib.sha256(contents).hexdigest()}}
        root.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='.translation-', dir=root) as tmp:
            stage = Path(tmp)
            (stage/'Spec.lean').write_bytes(contents)
            (stage/'identity.json').write_text(json.dumps(record, indent=2, sort_keys=True)+'\n')
            try:
                stage.rename(directory)
            except OSError as error:
                if error.errno not in (errno.EEXIST, errno.ENOTEMPTY):
                    raise
                # Concurrent emissions may prepare the same immutable selection.
                if directory.is_symlink() or source.is_symlink() or identity_path.is_symlink():
                    raise ValueError('shared translation path must not contain a symlink') from error
                if source.read_bytes() != contents or json.loads(identity_path.read_text()) != record:
                    raise ValueError('concurrent shared translation mismatch')
    return SharedTranslation(directory, module, {str(path): digest(path) for path in [source, identity_path]})
